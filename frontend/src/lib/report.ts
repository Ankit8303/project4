import type { ContractAnalysis } from "@/lib/schemas";

/** Calculate a 0-100 fairness score based on risk flags. */
export function calculateFairnessScore(analysis: ContractAnalysis): {
  score: number;
  label: "Critical Risk" | "High Risk" | "Moderate Risk" | "Mostly Fair" | "Clean";
  color: string;
} {
  if (analysis.flags.length === 0) {
    return { score: 100, label: "Clean", color: "text-emerald-500" };
  }

  // Deduct points based on severity
  let penalty = 0;
  for (const flag of analysis.flags) {
    switch (flag.severity_score) {
      case 5:
        penalty += 25;
        break;
      case 4:
        penalty += 15;
        break;
      case 3:
        penalty += 8;
        break;
      case 2:
        penalty += 4;
        break;
      case 1:
        penalty += 1;
        break;
    }
  }

  const score = Math.max(10, 100 - penalty);
  if (score < 40) return { score, label: "Critical Risk", color: "text-red-500" };
  if (score < 60) return { score, label: "High Risk", color: "text-orange-500" };
  if (score < 80) return { score, label: "Moderate Risk", color: "text-amber-500" };
  return { score, label: "Mostly Fair", color: "text-emerald-500" };
}

/** Formats the analysis as a markdown / docx-compatible audit report. */
export function generateMarkdownReport(analysis: ContractAnalysis): string {
  const health = calculateFairnessScore(analysis);
  const now = new Date().toLocaleDateString("en-IN", {
    year: "numeric",
    month: "long",
    day: "numeric",
  });

  const lines: string[] = [
    "# LEGAL RISK ASSESSMENT & CLAUSE AUDIT REPORT",
    `*Generated by NyayaShield · ${now}*`,
    "",
    "---",
    "",
    "## 1. EXECUTIVE SUMMARY",
    "",
    `* **Overall Fairness Score:** **${health.score} / 100** (${health.label})`,
    `* **Total Flagged Clauses:** ${analysis.flag_count}`,
    `* **Highest Severity Detected:** ${analysis.highest_severity?.toUpperCase() ?? "NONE"}`,
    `* **Applicable Jurisdiction:** ${analysis.jurisdiction}`,
    `* **Legal Statute Corpus:** ${analysis.corpus_version}`,
    "",
    "---",
    "",
    "## 2. DETAILED RISK AUDIT & STATUTORY CITATIONS",
    "",
  ];

  if (analysis.flags.length === 0) {
    lines.push("No unfair or legally questionable clauses were detected in this agreement.");
  } else {
    for (const [idx, flag] of analysis.flags.entries()) {
      lines.push(`### Clause ${idx + 1}: ${flag.clause_heading ?? flag.clause_type.toUpperCase()}`);
      lines.push(
        `* **Risk Severity:** Level ${flag.severity_score}/5 (${flag.severity_label.toUpperCase()})`,
      );
      lines.push(`* **Category:** ${flag.clause_type.replace(/_/g, " ")}`);
      lines.push("");
      lines.push("> **Current Contract Text:**");
      lines.push(`> "${flag.clause_excerpt}"`);
      lines.push("");
      lines.push(`**Legal Rationale:** ${flag.rationale}`);
      lines.push("");

      if (flag.citations && flag.citations.length > 0) {
        lines.push("**Statutory Backing under Indian Law:**");
        for (const c of flag.citations) {
          lines.push(`- **${c.reference}** — *${c.section_title}*`);
          lines.push(`  "${c.snippet.slice(0, 300)}..."`);
        }
        lines.push("");
      }

      if (flag.suggested_revision) {
        lines.push("**Proposed Fair Counter-Clause (Redline):**");
        lines.push("```text");
        lines.push(flag.suggested_revision);
        lines.push("```");
        lines.push("");
      }

      if (flag.negotiation_rationale) {
        lines.push(`*Negotiation Strategy:* ${flag.negotiation_rationale}`);
        lines.push("");
      }

      if (flag.negotiation_email_snippet) {
        lines.push("**Ready-to-Send Negotiation Script:**");
        lines.push(`> "${flag.negotiation_email_snippet}"`);
        lines.push("");
      }

      lines.push("---");
      lines.push("");
    }
  }

  lines.push("## 3. LEGAL DISCLAIMER");
  lines.push(analysis.disclaimer);
  lines.push("");

  return lines.join("\n");
}

/** Trigger download of a text or markdown report file in the browser. */
export function downloadTextFile(
  filename: string,
  content: string,
  mimeType = "text/markdown",
): void {
  const blob = new Blob([content], { type: `${mimeType};charset=utf-8` });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
